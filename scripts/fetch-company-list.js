// scripts/fetch-company-list.js
import fs from 'fs';
import axios from 'axios';
import iconv from 'iconv-lite';
import Soup from 'soup'; // 這個套件回傳的是包著 HTML 的容器（有 _string / toString）

const TSE = 'https://isin.twse.com.tw/isin/C_public.jsp?strMode=2';
const OTC = 'https://isin.twse.com.tw/isin/C_public.jsp?strMode=4';

const DEBUG = String(process.env.DEBUG || '').toLowerCase() === 'true';

async function fetchHtml(url) {
  const { data } = await axios.get(url, {
    responseType: 'arraybuffer',
    headers: { 'User-Agent': 'Mozilla/5.0', 'Accept-Language': 'zh-TW,zh;q=0.9' },
    timeout: 30000,
  });
  const htmlBig5 = iconv.decode(Buffer.from(data), 'big5');
  if (DEBUG) {
    console.log(`[debug] fetched ${url}, length=${htmlBig5.length}`);
    fs.mkdirSync('output', { recursive: true });
    fs.writeFileSync(`output/debug-${url.includes('strMode=2') ? 'tse' : 'otc'}.html`, htmlBig5);
  }
  return htmlBig5;
}

// 簡單的 HTML 去標籤＋實體還原
function stripTags(s) {
  if (!s) return '';
  return s
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

/** 用 Soup 取得 html 字串，再用 regex 解析表格 */
function parseWithSoup(html, market) {
  // 1) 用 soup 包裝字串（這個套件本質上就是字串容器）
  const doc = new Soup(html);
  const s = (typeof doc.toString === 'function') ? doc.toString() : (doc._string || String(doc));

  // 2) 取出 <table class="h4"> 的內容
  const tableMatch = s.match(/<table[^>]*class=['"]?h4['"]?[^>]*>([\s\S]*?)<\/table>/i);
  if (!tableMatch) {
    if (DEBUG) console.log('[debug] 找不到 table.h4');
    return [];
  }
  const tableHtml = tableMatch[1];

  // 3) 切出每個 <tr>，並抽取 <td>
  const trRegex = /<tr[^>]*>([\s\S]*?)<\/tr>/gi;
  const tdRegex = /<td[^>]*>([\s\S]*?)<\/td>/gi;

  const out = [];
  let trMatch;
  while ((trMatch = trRegex.exec(tableHtml)) !== null) {
    const trHtml = trMatch[1];

    // 分類列通常是「<td colspan=7> 股票 </td>」→ 沒有多個 <td> 可跳過
    const cells = [];
    let tdMatch;
    while ((tdMatch = tdRegex.exec(trHtml)) !== null) {
      cells.push(stripTags(tdMatch[1]).replace(/\s+/g, ' ').replace(/\u3000/g, ' ').trim());
    }
    if (cells.length < 5) continue; // 跳過表頭或分類列

    // 第一欄通常為「1101 台泥」或「1101　台泥」（含全形空白）
    const idName = cells[0];
    const m = idName.match(/^(\d{4})\s+(.+)$/);
    if (!m) continue;

    const id = m[1];
    const name = m[2].trim();

    // 過濾 ETF / 權證 / 債 / 基金…（用名稱與其他欄位合併判斷）
    const joined = cells.join(' ');
    if (/受益|債|認購|認售|權證|ETF|ETN|不動產投資信託|基金/i.test(joined)) continue;

    out.push({ id, name, market });
  }

  return out;
}

function parse(html, market) {
  // 只用 soup＋regex 解析（不依賴 cheerio / DOM API）
  const rows = parseWithSoup(html, market);
  if (DEBUG) console.log(`[debug] ${market} rows: ${rows.length}`);
  return rows;
}

async function run() {
  console.log('➡️ 抓取上市公司清單…');
  const listedHtml = await fetchHtml(TSE);
  const listed = parse(listedHtml, 'TWSE');

  console.log('➡️ 抓取上櫃公司清單…');
  const otcHtml = await fetchHtml(OTC);
  const otc = parse(otcHtml, 'TPEx');

  const all = [...listed, ...otc].sort((a, b) => a.id.localeCompare(b.id));

  console.log(`\n✅ 抓取完成：上市 ${listed.length} 筆，上櫃 ${otc.length} 筆，合計 ${all.length} 筆`);
  console.table(all.slice(0, 30));

  fs.mkdirSync('output', { recursive: true });
  fs.writeFileSync('output/companies.json', JSON.stringify(all, null, 2));
  fs.writeFileSync(
    'scripts/company-list.js',
    `// generated by fetch-company-list
export const COMPANIES = ${JSON.stringify(all, null, 2)};
`
  );
  console.log(`\n💾 已輸出 → output/companies.json、scripts/company-list.js`);
}

run().catch((e) => {
  console.error('❌ 抓取失敗：', e.stack || e.message);
  process.exit(1);
});